#!/usr/bin/env node
/**
 * Generates a fresh 256-bit AES Master Key for the OpenCreche Privacy Vault
 * and initializes the gitignored `.vault-raw/` directory with sample YAML templates.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const envPath = path.resolve('.env');
const rawDir = path.resolve('.vault-raw');

const newKey = crypto.randomBytes(32).toString('base64');

if (!fs.existsSync(envPath)) {
  fs.writeFileSync(
    envPath,
    `# Generated by scripts/generate-keys.mjs\nVAULT_MASTER_KEY="${newKey}"\n`,
    'utf-8'
  );
  console.log('✅ Created .env with a fresh 256-bit VAULT_MASTER_KEY');
} else {
  console.log('ℹ️  .env already exists. Skipping key overwrite.');
}

fs.mkdirSync(path.join(rawDir, 'media', 'staff'), { recursive: true });
fs.mkdirSync(path.join(rawDir, 'media', 'gallery'), { recursive: true });

console.log('✅ Initialized .vault-raw/ directory structure (gitignored).');
console.log('👉 Run `npm run vault:demo` or `npm run vault:encrypt` to build encrypted vault files.');
